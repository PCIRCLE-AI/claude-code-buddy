#!/usr/bin/env node
// Translate README.md into target languages using Anthropic Claude.
//
// Single source of truth: README.md (English).
// Targets: README.<lang>.md for each language code passed via --targets.
//
// Usage:
//   node scripts/translate-readme.mjs --source README.md --targets de,es,fr,ja,ko,pt,th,vi,zh-CN
//
// The script:
//   - Reads the English README
//   - Calls Anthropic with a translate-faithfully prompt (preserves code
//     blocks, links, structure, version numbers verbatim — only translates
//     prose)
//   - Writes each target file with a header comment noting the source
//     commit it was synced from
//   - Skips a target when an existing localized README already starts with
//     that source-commit marker (idempotent re-runs)
//
// Requires ANTHROPIC_API_KEY env var.

import { readFileSync, writeFileSync, existsSync } from 'fs';
import { execFileSync } from 'child_process';

const args = process.argv.slice(2);
function arg(name, dflt) {
  const i = args.indexOf(`--${name}`);
  return i >= 0 ? args[i + 1] : dflt;
}

const SOURCE = arg('source', 'README.md');
const TARGETS = (arg('targets', 'de,es,fr,ja,ko,pt,th,vi,zh-CN') || '').split(',').map(s => s.trim()).filter(Boolean);
const MODEL = arg('model', 'claude-haiku-4-5');

if (!process.env.ANTHROPIC_API_KEY) {
  console.error('ANTHROPIC_API_KEY not set; cannot translate.');
  process.exit(2);
}

if (!existsSync(SOURCE)) {
  console.error(`Source ${SOURCE} not found.`);
  process.exit(2);
}

const sourceText = readFileSync(SOURCE, 'utf8');
const sourceCommit = (() => {
  try {
    return execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
  } catch {
    return 'unknown';
  }
})();

const LANGUAGE_NAMES = {
  de: 'German', es: 'Spanish', fr: 'French', ja: 'Japanese', ko: 'Korean',
  pt: 'Portuguese', th: 'Thai', vi: 'Vietnamese', 'zh-CN': 'Simplified Chinese',
  'zh-TW': 'Traditional Chinese',
};

async function translate(text, targetLang) {
  const langName = LANGUAGE_NAMES[targetLang] ?? targetLang;
  const prompt = [
    `You are translating a technical project README from English into ${langName}.`,
    '',
    'Hard rules:',
    '- Preserve every code block, command, file path, URL, package name, and version number EXACTLY (do not translate).',
    '- Preserve every Markdown heading level, list, table, and emoji.',
    '- Translate ONLY the prose; keep technical identifiers (npm package names, env var names, function names) unchanged.',
    '- Do NOT add, remove, or reorder sections.',
    '- Do NOT explain or summarize. Output only the translated README, nothing else.',
    '',
    'BEGIN ENGLISH SOURCE:',
    text,
    'END ENGLISH SOURCE.',
  ].join('\n');

  const r = await fetch('https://api.anthropic.com/v1/messages', {
    method: 'POST',
    headers: {
      'x-api-key': process.env.ANTHROPIC_API_KEY,
      'anthropic-version': '2023-06-01',
      'content-type': 'application/json',
    },
    body: JSON.stringify({
      model: MODEL,
      max_tokens: 8000,
      messages: [{ role: 'user', content: prompt }],
    }),
  });
  if (!r.ok) {
    const body = await r.text();
    throw new Error(`Anthropic ${r.status}: ${body.slice(0, 200)}`);
  }
  const data = await r.json();
  const block = data.content?.[0];
  if (!block || block.type !== 'text') throw new Error('No text content in response');
  return block.text;
}

const HEADER_RE = /^<!-- translated from README\.md @ ([0-9a-f]{8,40}) -->/m;

for (const lang of TARGETS) {
  const dest = `README.${lang}.md`;
  if (existsSync(dest)) {
    const existing = readFileSync(dest, 'utf8');
    const match = existing.match(HEADER_RE);
    if (match && match[1] === sourceCommit) {
      console.log(`[skip] ${dest} already synced to ${sourceCommit.slice(0, 8)}`);
      continue;
    }
  }
  console.log(`[translate] ${dest} (${LANGUAGE_NAMES[lang] ?? lang})`);
  let body;
  try {
    body = await translate(sourceText, lang);
  } catch (err) {
    console.error(`  failed: ${err.message}`);
    process.exitCode = 1;
    continue;
  }
  const header = `<!-- translated from README.md @ ${sourceCommit} -->\n<!-- DO NOT edit this file by hand. Edit README.md and re-run scripts/translate-readme.mjs (or push to main; CI will sync). -->\n\n`;
  writeFileSync(dest, header + body.trim() + '\n');
  console.log(`  wrote ${dest} (${body.length} chars)`);
}
